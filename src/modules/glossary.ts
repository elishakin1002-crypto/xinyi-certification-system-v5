/**
 * 术语表 —— 一个概念一个词，全系统引用这里。
 *
 * ══════════════════════════════════════════════════════════════
 * 为什么要有这个文件
 * ══════════════════════════════════════════════════════════════
 *
 * 金恩来 2026-09-15：「这个系统的字段是否统一，这块是基础啊，
 *   否则后面会越做越乱……如果功能一样就要统一字段，
 *   而且字段要和实际功能挂钩，不能词不达意。」
 *
 * 他是对的，而且这不是文案问题，是**设计问题**。把所有角色的头部卡片
 * 摊开之后，同一个概念有三四种说法：
 *
 *   状态=进行中的项目   在制项目总数 / 当前在制项目数 / 进行中项目 / 人均在制项目数
 *   状态=已完成的项目   已完成项目（卡片） vs 已结项（状态标签）—— 同一页两个词
 *   过了截止日没做完   已逾期任务 / 逾期任务数 / 逾期未完成任务 / 未完成任务
 *
 * 后果不是"看着乱"，是**人无法判断两个数字该不该相等**：
 * 工作台写「逾期任务数 5」，项目管理写「逾期未完成任务 0」，
 * 同事第一反应是系统坏了，而不是"这两个统计口径不同"。
 *
 * ── 做法：领域驱动设计里的 Ubiquitous Language（统一语言）──────
 *
 * 成熟团队的标准做法不是"写一份术语文档让大家遵守"（那属于
 * CLAUDE.md 二点五第 4 条：要人记住的规矩早晚有人记不住），
 * 而是**把术语落成代码里的常量，界面引用常量**。
 * 想用别的说法就得改这里，改这里就会被 review 看到。
 *
 * 配套一条测试（tests/glossary.test.js）扫描界面文案，
 * 出现"同义异名"直接红 —— 这样它才是机制，不是倡议。
 *
 * ── 每条术语必须写清「口径」──────────────────────────────────
 *
 * 只定名字不定口径，等于没统一：两个页面都叫「逾期任务」，
 * 一个算已结项项目里的、一个不算，照样对不上。
 * 所以每条都写明**数的是什么、包不包括什么**。
 */

/** 项目状态相关 */
export const TERM_PROJECT = {
  /**
   * 进行中的项目。
   *
   * 口径：status === Active。
   * 不用「在制」——那是制造业说在制品，咨询公司不这么讲话。
   */
  active: '进行中项目',

  /**
   * 已经结项的项目。
   *
   * 口径：status === Completed。
   * 用「已结项」不用「已完成」：结项是这行的正式说法，
   * 而且它是一个**有仪式的动作**（要走完结清单、生成 PDCA），
   * 和"任务完成""合同完成"不是一回事。
   * 之前项目管理的卡片写「已完成项目」、状态标签写「已结项」，
   * 同一页两个词，人会以为是两种状态。
   */
  completed: '已结项',

  /** 进行中、且名下有逾期任务的项目。口径：Active && tasks.some(isOverdue) */
  withOverdueTask: '有逾期任务的项目',
} as const;

/** 任务状态相关 */
export const TERM_TASK = {
  /**
   * 还没做完的任务。
   *
   * 口径：isOpenTask() —— 即 status 不是 Completed 也不是 Skipped。
   * 「跳过」算了结：人已经交代过为什么不做了。
   */
  open: '未完成任务',

  /**
   * 过了截止日期还没做完的任务。
   *
   * 口径：isOverdue()，**而且只算进行中项目里的**。
   *
   * 后半句是 2026-09-15 才定的。在此之前工作台把已结项项目里
   * 没勾完的任务也算进来，于是顾问看到「进行中项目 0 / 逾期任务 5」——
   * 一个永远消不掉的红色数字。
   * 已结项项目里的残留任务是**收尾没做干净的记录问题**，
   * 该在结项那一刻处理，不该天天挂在人的待办上。
   * 一个永远消不掉的红，会让人不再信任所有的红。
   */
  overdue: '逾期任务',

  /** 未来 7 天内到期、还没做完的任务 */
  dueSoon: '即将到期任务',
} as const;

/** 回款相关 */
export const TERM_RECEIVABLE = {
  /**
   * 过了约定收款日还没收到的款。
   *
   * 口径：status !== paid && dueDate < 今天。**不限时间窗口**。
   * 「逾期」是财务行业术语（逾期账款），不用「超期」。
   */
  overdue: '逾期回款',
  /** 未来 30 天内到期的应收 */
  upcoming: '未来30天预计回款',
} as const;

