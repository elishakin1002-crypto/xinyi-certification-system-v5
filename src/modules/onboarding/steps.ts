/**
 * 新手引导：按角色讲「你打开这个系统，第一件事该做什么」。
 *
 * ── 为什么按角色分，不做一套通用的 ────────────────────────────
 * 通用引导会把所有功能都过一遍，而顾问根本用不到财务、
 * 财务也不管交付进度。看一堆和自己无关的东西，
 * 结果是**该记住的那三步反而没记住**。
 *
 * ── 为什么只讲四到六步 ────────────────────────────────────────
 * 引导的目的不是教会全部功能，是让人**今天能把活干完**。
 * 十步以上的引导，人会从第四步开始一路点「下一步」，等于没看。
 *
 * ── 既要说「为什么」，也要说「点哪里、填什么」（2026-09-06）────
 *
 * 原来每一步只讲道理：「客户是老板谈来的，你记进来系统才知道提醒谁跟进」。
 * 道理是对的，也确实比「点这里新建线索」好记 —— 但**只有道理落不了地**：
 * 合上引导之后，人还是不知道第一下点哪儿。
 *
 * 所以现在每一步分两层：
 *   body   —— 为什么要做这件事（接上他本来就懂的事）
 *   howTo  —— 具体怎么做，一步一行，按钮名和界面上完全一致
 *
 * 按钮名必须和界面对得上。写「点新建」而界面上写着「新增线索」，
 * 人会以为自己找错地方了 —— 这比不写还糟。
 *
 * ── 手机和电脑要分开写 ────────────────────────────────────────
 * 手机上左侧导航是收起来的，「左边点项目管理」这句话在手机上是错的。
 * 有差别的步骤单独写一份 howToMobile；没写就沿用电脑那份，
 * 组件会自动在前面提示「先点左上角 ☰」。
 */

export interface OnboardStep {
  /** 高亮哪个元素。用 data-onboard 属性选，不用 class —— class 改样式时会被误删 */
  target?: string;
  title: string;
  /** 为什么要做这件事 */
  body: string;
  /** 具体怎么操作，一步一行。按钮名要和界面完全一致 */
  howTo?: string[];
  /** 手机上做法不同时才写。留空 = 沿用 howTo */
  howToMobile?: string[];
  /** 引导到这一步时把人带到哪个页面 */
  route?: string;
}

export interface OnboardTour {
  /** 版本号。内容有实质更新时 +1，看过旧版的人会再看一次新版 */
  version: number;
  intro: string;
  steps: OnboardStep[];
}

