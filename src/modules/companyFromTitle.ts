/**
 * 从合同标题里猜出对方公司名。
 *
 * ── 为什么要有这个（2026-09-14 金恩来提的设计）─────────────────
 *
 * 他说：「在合同管理中新建合同时若是没有现成的关联客户，需要新建客户，
 *        点新建客户时默认直接把合同里对方公司的名字填上去，
 *        若不是的话新建合同的人也可以自己删了重新写。这个能力需要调用 AI 吗？」
 *
 * **不需要。** 信义的合同标题本身就带着公司全称：
 *   「优福包装科技（浙江）有限公司 咨询服务合同书」
 *   「浙江博峰数字科技有限公司 ISO9001 认证咨询服务合同」
 * 把「合同书 / 服务合同 / 认证咨询」这类文书名和认证标准号去掉，剩下的就是公司名。
 *
 * 上传 PDF 时有 AI 识别出的甲方名（走 aiContractCustomerName 那条路，更准），
 * 这里补的是**手工录入**那条路 —— 那时候页面上除了标题没有别的地方有公司名。
 *
 * ── 分寸：猜错了不要紧，猜不出来才要紧 ────────────────────────
 *
 * 这个结果是**填进输入框的默认值**，人看得见、改得动。
 * 所以宁可多留几个字（人删两下），也不要为了"干净"把公司名本身削掉 ——
 * 一个被削成「优福包装」的名字，人不一定会注意到，
 * 而客户档案里存错全称，以后开票、发证书都要返工。
 */

/** 文书类型后缀。按长到短排，否则「合同」会先把「咨询服务合同书」切成「咨询服务…书」 */
const DOC_SUFFIXES = [
  '咨询服务合同书', '技术服务合同书', '咨询服务协议书', '技术服务协议书',
  '咨询服务合同', '技术服务合同', '认证咨询合同', '服务合同书', '咨询合同',
  '服务协议书', '服务合同', '服务协议', '合作协议', '委托合同', '委托协议',
  '合同书', '协议书', '合同', '协议',
];

/**
 * 认证标准/服务类型的关键词。出现在标题里时一并去掉。
 *
 * 只列**明确是服务名而不可能是公司名一部分**的。
 * 像「包装」「食品」这种词绝不能进来 —— 它们是公司名的常见组成部分
 * （温州康田包装有限公司），删了就把公司名弄坏了。
 */
const SERVICE_TOKENS = [
  'ISO9001', 'ISO 9001', 'ISO14001', 'ISO 14001', 'ISO45001', 'ISO 45001',
  'ISO22000', 'ISO 22000', 'ISO13485', 'ISO 13485', 'IATF16949', 'IATF 16949',
  'HACCP', 'BRC', 'FSSC', 'QS', 'SC',
  '质量管理体系认证', '环境管理体系认证', '职业健康安全管理体系认证',
  '食品安全管理体系认证', '管理体系认证', '体系认证', '认证咨询', '认证辅导',
  '生产许可证', '生产许可', '台账指导', '验厂辅导', '内审员培训',
];

/** 公司名的常见结尾。找到它就以它为界 —— 比逐个删后缀可靠得多 */
const COMPANY_TAILS = [
  '有限责任公司', '股份有限公司', '有限公司', '专业合作社', '合作社',
  '集团', '厂', '店', '中心', '事务所', '研究院', '研究所',
];

/**
 * @param title 合同标题
 * @returns 猜出来的公司名；猜不出返回空字符串（调用方就让人自己填）
 */
export const guessCompanyFromContractTitle = (title?: string): string => {
  const raw = String(title || '').trim();
  if (!raw) return '';

  /*
    先找公司名结尾。这是最可靠的一招：
    中文公司全称几乎一定以「有限公司」「合作社」「厂」之类收尾，
    找到最靠后的那个，从头截到它，剩下的就是完整公司名。

    为什么取**最靠后**的一个：标题里可能出现两次公司性质的词
    （「XX有限公司与YY有限公司合作协议」），取最后一个能把两边都留住，
    人一眼看出不对会自己改；取第一个则会悄悄丢掉一方。
  */
  let cut = -1;
  let cutTail = '';
  for (const tail of COMPANY_TAILS) {
    const idx = raw.lastIndexOf(tail);
    if (idx >= 0 && idx + tail.length > cut) {
      cut = idx + tail.length;
      cutTail = tail;
    }
  }
  if (cut > 0) {
    const head = raw.slice(0, cut).trim();
    // 截出来的东西太短，多半是匹配到了别的词（比如标题就叫「中心机房改造合同」）
    if (head.length >= 4 && head !== cutTail) return head;
  }

  /*
    没有公司性质词的标题（个体户、或者标题本来就写得随意），
    退回到"削后缀"：去掉文书名和服务名，剩下什么算什么。
  */
  let s = raw;
  for (const token of SERVICE_TOKENS) {
    s = s.split(token).join(' ');
  }
  for (const suffix of DOC_SUFFIXES) {
    if (s.trim().endsWith(suffix)) {
      s = s.trim().slice(0, -suffix.length);
      break;                        // 只削一次，避免把「合作社」削成「合作」
    }
  }
  s = s.replace(/[（(][^）)]*[）)]\s*$/, (m) => m)   // 结尾的括号内容保留（「（浙江）」是名字的一部分）
    .replace(/\s+/g, ' ')
    .replace(/^[·、,，\-—\s]+|[·、,，\-—\s]+$/g, '')
    .trim();

  // 剩不下几个字就等于没猜出来 —— 与其填个残缺的，不如让人自己写
  return s.length >= 4 ? s : '';
};
