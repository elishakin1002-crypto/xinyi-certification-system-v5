/**
 * 检测「空头承诺」：模型说了「请稍候」「正在处理」，但没输出任何动作块。
 *
 * ── 为什么会出这种事 ──────────────────────────────────────────
 * 对话框**只在同一轮执行动作**——把 `<execute_action>` 块解析出来、执行、显示结果。
 * 没有「稍后」这回事：这一轮结束，就不会再有动作发生。
 *
 * 但模型是按聊天习惯说话的，它会讲「现在为您重新执行系统自检，请稍候」，
 * 然后**什么动作块都不输出**。界面就停在那句话上，用户等了两分钟以为系统卡死了。
 *
 * 2026-08-31 老板反馈「机器人还是坏的」，实际就是这个：
 * 机器人前一轮明明正常跑完了自检，下一轮说了句「请稍候」就没下文了。
 * 从用户角度看，这和真的坏掉没有区别——**而且更糟，因为它看起来像在工作**。
 *
 * ── 两道防线 ────────────────────────────────────────────────
 * ① 提示词里明确禁止说「稍候」（治本，但提示词是软约束）
 * ② 这个函数（兜底）：模型没听话时，当场告诉用户「它没真的开始做」
 */

/** 表示「我等下会做」的说法。只匹配承诺，不匹配「稍等我想一下」这类语气词 */
/*
  中间常会插「为您」「重新」这类词（「正在**为您**处理」），
  所以动词前面统一留出可选插入位——第一版写死了「正在处理」，
  漏掉了「正在为您处理」这种最常见的说法。
*/
const DOING = '(执行|处理|运行|操作|查询|检查)';
const PROMISE_PATTERNS = [
  /请稍候/, /请稍等/, /稍后为?您?/,
  new RegExp(`正在(为您)?(重新)?${DOING}`),
  new RegExp(`马上(为您)?(重新)?${DOING}`),
  new RegExp(`立即(为您)?(重新)?${DOING}`),
  new RegExp(`这就(为您)?(重新)?${DOING}`),
  new RegExp(`我来(为您)?(重新)?${DOING}`),
];

const HAS_ACTION = /<execute_action>[\s\S]*?<\/execute_action>/;

/**
 * @param rawReply  模型的原始回复（**必须是没去掉动作块的原文**）
 * @returns 是不是一句没有后续的空头承诺
 */
export const isEmptyPromise = (rawReply: string): boolean => {
  const text = String(rawReply || '');
  if (!text.trim()) return false;
  if (HAS_ACTION.test(text)) return false;         // 有动作块，不算空头
  return PROMISE_PATTERNS.some((re) => re.test(text));
};

/** 给用户看的提示。要说清「不是坏了」，也要说清「你该怎么办」 */
export const EMPTY_PROMISE_NOTICE =
  '⚠️ 上面这条只是回复，**没有真的开始执行**。\n\n' +
  '我只能在回答的同一时刻执行操作，没有「稍后再做」这回事。' +
  '如果你确实要做那件事，请再说一次，比如把要做的事直接讲明白（「现在做系统自检」）。';
