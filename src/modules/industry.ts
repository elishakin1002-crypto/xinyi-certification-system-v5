/** 把一个工商口径的行业值归到信义口径的大类 */
export const groupIndustry = (raw?: string): IndustryGroup => {
  const t = String(raw || '').trim();
  if (!t || t === '待 AI 分析') return '其他';
  const hit = RULES.find(r => r.keys.test(t));
  return hit ? hit.group : '其他';
};

/** 两家公司算不算「同行」—— 决定经验和体系文件能不能互相借鉴 */
export const isSameIndustryGroup = (a?: string, b?: string): boolean => {
  const ga = groupIndustry(a);
  const gb = groupIndustry(b);
  return ga === gb && ga !== '其他';
};

