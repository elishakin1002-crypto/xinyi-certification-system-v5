/**
 * 行业归类 —— 把工商口径的细分行业，归到信义按业务实际区分的大类。
 *
 * ══════════════════════════════════════════════════════════════
 * 为什么必须有这一层（2026-09-08）
 * ══════════════════════════════════════════════════════════════
 *
 * 金恩来 2026-09-08：「基本上只要这个行业我们之前做过，
 * 大部分的体系文件是可以复用的，就是改一下公司抬头和部分数据！」
 *
 * **这是信义最核心的效率来源。** 但线上实测：
 *
 *   466 条客户/线索记录，散在 **180 个不同的行业值**里，
 *   其中 110 个只出现过一次。
 *
 * 因为存的是工商注册口径 ——「包装装潢及其他印刷」「其他纸制品制造」
 * 「纸和纸板容器制造」「塑料包装箱及容器制造」在工商是四个行业，
 * **在信义眼里是同一件事：包装厂**，体系文件互相能抄。
 *
 * 于是「同行业做过就能复用」这条最值钱的资产，
 * **在系统里根本查不出来** —— 按行业找，同行业永远只有一家。
 *
 * 这一层就是把那 180 个值归到十来个「信义口径」的大类。
 *
 * ── 为什么用关键词规则，不用枚举映射 ──────────────────────────
 *
 * 行业值来自工商数据，是**开放集合** —— 明天来个新客户就可能带来
 * 第 181 个值。逐条枚举的表永远补不完，而补不上的那些会静默落进
 * 「其他」，然后没人知道。
 *
 * 关键词规则对没见过的值也能归对：「XX 包装制品制造」里有「包装」，
 * 「XX 塑胶模具」里有「模具」。**规则的顺序就是优先级**，
 * 具体的写在前面（「包装专用设备」是设备不是包装厂）。
 *
 * ── 归错了怎么办 ──────────────────────────────────────────────
 *
 * 归错的代价很小：检索时多看/少看几篇同行业的资料。
 * 所以**宁可归得粗一点**，也不要为了准确切出三十个大类 ——
 * 那等于没归。
 *
 * 校验：`npm run checkup:industry` 会打印归类后的分布，
 * 以及仍然落进「其他」的原始值，用来判断规则该不该补。
 */

