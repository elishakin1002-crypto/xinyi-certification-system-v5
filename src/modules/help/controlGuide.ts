/**
 * ③ 单项解释 —— 「这个按钮/这一栏是什么意思？」
 *
 * ── 为什么是一张规则表，而不是给每个控件挂 id ────────────────
 *
 * 全系统有上千个按钮、字段、徽章。要一个个挂 `data-help="xxx"`，
 * 得改遍每一个页面，而且以后每加一个按钮就多一处会忘的地方 ——
 * 忘了的那些，点上去就是「暂无说明」，比没有这个功能更让人失望。
 *
 * 参考金恩来另一个项目（LH 酱菜厂）的做法：**按名字匹配**。
 * 界面上的名字本来就是给人看的，「确认到账」「停用」「转为客户」
 * 这些词在哪一页都是同一个意思。一条规则覆盖它出现的所有地方，
 * 新页面只要沿用同样的措辞，说明自动就有了。
 *
 * 匹配不上时不说「暂无说明」，而是按控件种类给一句通用的
 * （见 FALLBACK_BY_KIND）—— 至少告诉他这是个下拉、点了会筛选。
 *
 * ── 每条说明写什么 ────────────────────────────────────────────
 *
 *   what  这是什么、点了会发生什么
 *   why   为什么这样设计 / 什么时候该用它
 *   warn  会造成什么后果（不可撤销、会通知别人、会进审计）——只有真有后果才写
 *
 * 措辞上有一条硬规矩：**每条都要纠正一个具体的误解**。
 * 「点击保存以保存数据」这种话等于没写，还占着人的注意力。
 */

export type ControlKind = 'button' | 'link' | 'select' | 'input' | 'checkbox' | 'tab' | 'badge' | 'text';

export interface ControlHelp {
  what: string;
  why?: string;
  warn?: string;
}

interface Rule {
  match: RegExp;
  /** 限定只在某类控件上生效。不写 = 任何控件 */
  kind?: ControlKind[];
  help: ControlHelp;
}

