/**
 * 给一个控件名找解释。
 *
 * @param name 界面上显示的名字（按钮文字、aria-label、title）
 * @param kind 控件种类，用来在名字含糊时选对措辞
 */
export const explainControl = (name: string, kind: ControlKind = 'button'): ControlHelp & { matched: boolean } => {
  const text = String(name || '').replace(/\s+/g, ' ').trim();
  if (text) {
    const hit = RULES.find(r => (!r.kind || r.kind.includes(kind)) && r.match.test(text));
    if (hit) return { ...hit.help, matched: true };
  }
  return { ...FALLBACK_BY_KIND[kind], matched: false };
};

