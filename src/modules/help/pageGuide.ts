/**
 * ② 本页详解 —— 「我现在在的这一页，到底是干什么的？」
 *
 * ── 三层帮助里的第二层 ────────────────────────────────────────
 *
 *   ① 岗位上手：我这个岗位，进来先干什么   → 一次性，走一遍
 *   ② 本页详解：眼前这一页是干什么的        → 随时看，就在这一页
 *   ③ 单项解释：这个按钮/这一栏是什么意思    → 指哪讲哪
 *
 * 第一层解决「从零开始」，第三层解决「这个东西是什么」。
 * 中间这一层解决的是**最常见的那种卡住**：
 * 每个按钮我都认识，但我不知道这一页整体上要我干嘛、按什么顺序干。
 *
 * ── 为什么按「四个问题」写，而不是写一段介绍 ──────────────────
 *
 * 参考金恩来另一个项目（LH 酱菜厂）的做法，那套的模块介绍固定回答四问：
 * 这个模块负责什么 / 通常按什么顺序使用 / 各区域怎么分工 / 然后去哪操作。
 *
 * 固定四问有两个好处：写的人不会漏，看的人知道答案在第几段。
 * 一段自由发挥的介绍，读完往往还是不知道「那我现在该点哪」。
 *
 * 我在四问之外加了第五条 `misread`：**这一页最容易被误会的那件事**。
 * 因为真正让人卡住的从来不是「不知道」，是「以为自己知道」——
 * 比如以为「与我相关」是权限（其实只是筛选）、
 * 以为「跟进项目」也算营收（其实不算）。
 *
 * ── 弹窗要单独讲 ──────────────────────────────────────────────
 *
 * 人最需要解释的时刻，恰恰是弹窗开着、面前一堆必填项的时候。
 * 这时候讲「项目管理页分三块」毫无用处。所以打开帮助时先看有没有弹窗，
 * 有就讲弹窗，没有才讲整页。弹窗按标题认（见 MODAL_GUIDES），
 * 这样各页面不用为了帮助去改代码。
 */

export interface GuideEntry {
  /** 页面/弹窗的名字，显示在帮助卡片标题上 */
  title: string;
  /** 这个模块负责什么 —— 一句话，说清它在业务里的位置 */
  what: string;
  /** 通常按什么顺序使用 —— 一步一行 */
  order: string[];
  /** 各区域怎么分工 */
  areas: { name: string; role: string }[];
  /** 这一页最容易被误会的那件事 */
  misread?: string;
}

