/** 按当前路由找页面说明。找不到返回 null —— 帮助面板会退回讲通用的那几句 */
export const findPageGuide = (pathname: string): GuideEntry | null => {
  const path = String(pathname || '').split('?')[0];
  // 长的优先，`/finance/settlements` 要能落到 `/finance`
  const hit = PAGE_GUIDES
    .slice()
    .sort((a, b) => b.path.length - a.path.length)
    .find(p => path === p.path || path.startsWith(`${p.path}/`));
  return hit ? hit.guide : null;
};

/** 按弹窗标题找说明 */
export const findModalGuide = (heading: string): GuideEntry | null => {
  const text = String(heading || '').trim();
  if (!text) return null;
  const hit = MODAL_GUIDES.find(m => m.match.test(text));
  return hit ? hit.guide : null;
};
