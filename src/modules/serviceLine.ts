/**
 * 一眼就能看出「这不是服务名，是项目名/合同名」的写法。
 *
 * 默认服务项是拿项目名命名的（buildDefaultServiceItem），
 * 于是库里一大半服务项叫「XX公司 咨询服务合同书」「XX公司 认证到期挖角跟进」。
 * 这些**不是没归对，是压根不该参与归类** —— 硬按关键词去套，
 * 「咨询服务合同书」会命中一堆规则，归出来的结果纯属噪音。
 */
const NOT_A_SERVICE = /咨询服务合同书|认证到期(挖角)?跟进|情报跟进|服务合同$|^默认服务/;

/**
 * 这串文本**像不像一个服务名**。
 *
 * 为什么要单独有这个判断：库里一大半「服务项名称」其实是项目名
 * （「XX公司 咨询服务合同书」），它们归不出类是**对的**，不是规则的漏洞。
 *
 * 两者混在一起会得出完全错误的结论 —— 2026-09-11 第一次跑覆盖率，
 * 59 条里 30 条「未分类」，看起来规则只覆盖了一半；
 * 拆开才发现其中 26 条根本不是服务名，真正的规则漏洞只有 2 个。
 * **分母错了，结论就会错**，而错的方向是让人以为要大改规则。
 */
export const looksLikeServiceName = (raw?: string): boolean => {
  const text = String(raw || '').trim();
  if (!text) return false;
  return !NOT_A_SERVICE.test(text);
};

export const SERVICE_GROUPS: ServiceGroup[] = [
  '体系认证', '食品生产许可', '食品相关产品', '验厂', '科技申报', '职业卫生',
  '安全生产', '台账指导', '计量校准', '工商代理', '知识产权', '其他许可', '未分类',
];

export const groupServiceLine = (raw?: string): ServiceGroup => {
  const text = String(raw || '').trim();
  if (!looksLikeServiceName(text)) return '未分类';

  /*
    **传进来的如果本身就是大类名，直接认，别再走关键词规则。**

    2026-09-11 踩到：表单加了「服务类型」下拉之后，选中的值就是大类名本身
    （比如「体系认证」），而关键词规则里写的是 `管理体系|三体系|ISO…` ——
    「体系认证」这四个字**一条都不匹配**，于是归成「未分类」，
    建议一个人选都给不出来。

    更值得记的是**我的测试当时是绿的**：那条用例用的是「食品相关产品」，
    而它恰好出现在自己的关键词里（`/食品相关产品|食包|…/`），所以过了。
    换成「体系认证」就露馅 —— **抽样抽到了唯一能通过的那个**。
    所以下面那条测试改成遍历全部 12 个大类，不再挑一个代表。
  */
  const exact = SERVICE_GROUPS.find((g) => g === text);
  if (exact && exact !== '未分类') return exact;

  const hit = RULES.find((r) => r.keys.test(text));
  return hit ? hit.group : '未分类';
};

/** 两条服务是不是同一大类 —— 「未分类」永远不算同类，否则一堆认不出的会互相匹配 */
export const isSameServiceGroup = (a?: string, b?: string): boolean => {
  const ga = groupServiceLine(a);
  return ga === groupServiceLine(b) && ga !== '未分类';
};



