/**
 * 服务类型归类 —— 把自由文本的服务名，归到信义实际分工的大类。
 *
 * ══════════════════════════════════════════════════════════════
 * 为什么必须有这一层（2026-09-11）
 * ══════════════════════════════════════════════════════════════
 *
 * 金恩来 2026-09-10：「客户不是根据服务类型确定及分配的吗？」
 *
 * 对的，而且这条规则比「谁跟哪个客户」好得多 —— **它是可推导的**：
 * 花名册上每个人的方向写得清清楚楚（佳佳做食品厂 SC、春姿做食包、
 * 邦煜做体系认证），服务类型一定，负责人就定了，不用谁去维护一张对照表。
 *
 * 但系统当时**推不出来**，因为服务类型这个字段没有规范。线上实测：
 *
 *   · 合同 service_line：10 份合同 **10 种写法**
 *     「SC食品生产许可证」和「SC 食品生产许可」是同一件事，字符串不等
 *     「QS 食品相关产品生产许可证认证咨询服务」和「QS 食品相关产品生产许可」同理
 *   · 项目服务项名称：**大部分根本不是服务名**，是「XX公司 咨询服务合同书」
 *     —— 默认服务项拿项目名命名，于是真服务名被淹没在项目名里
 *   · 线索 target_certifications：**454 / 455 是空的**
 *   · project_type：全是 Self-Operated —— 那是自营/外包，不是服务类型
 *
 * 所以「按服务类型分配」这条本来最顺的规则，在系统里落不了地。
 *
 * ── 和行业归类是同一个问题 ────────────────────────────────────
 *
 * industry.ts 解决的是「180 个工商行业值 → 12 个信义大类」，
 * 这里解决的是「N 种服务写法 → 一组信义实际分工的大类」。
 * 做法照搬：**关键词规则 + 顺序即优先级**，不用枚举映射。
 *
 * 理由也一样：服务名是开放集合，明天就可能冒出第 N+1 种写法
 * （客户自己起的合同标题、新开的业务线）。逐条枚举的表永远补不完，
 * 补不上的会静默落进「其他」，然后没人知道。
 *
 * ── 大类怎么定的 ──────────────────────────────────────────────
 *
 * 不是我拍的，是照《信义在职员工表》的「岗位职责」倒推 ——
 * **有人专门做的才配当一个大类**，没人做的不单列：
 *
 *   体系认证      黄邦煜、梁杰（ISO 各体系、三体系/五体系、诚信、社会责任）
 *   食品生产许可  黄佳佳（食品厂 SC）
 *   食品相关产品  商春姿、陈诗蕾（食包 QS）
 *   验厂          梁杰（环球验厂、社会责任验厂）
 *   科技申报      郑园园（省科/国科/高新/技术中心）、曾瑞锨（技改）
 *   职业卫生      林元波（职业病危害检测、职业病体检）
 *   安全生产      曾瑞锨
 *   台账指导      温婵然、陈诗蕾、商春姿（食包/安全/职业卫生/文化台账）
 *   计量校准      商春姿（设备校准）
 *   工商代理      商春姿（营业执照、年检）
 *   知识产权      郑园园（专利、商标、软著）
 *   其他许可      医疗器械、饲料添加剂这类单独许可
 *
 * ── 归错了怎么办 ──────────────────────────────────────────────
 *
 * 和行业那层不同：**这里归错是有代价的** —— 活会派给不对的人。
 * 所以 ① 拿不准的一律落「未分类」，不硬猜；
 * ② 「未分类」在界面上要显式提示人工指定，不能静默吞掉。
 * 宁可让人多点一下，也不要把食品的活派给做职业卫生的。
 */

