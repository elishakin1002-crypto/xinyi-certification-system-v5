/**
 * 知识库文档的可见范围 —— 谁永远看得见，不由上传的人决定。
 *
 * ══════════════════════════════════════════════════════════════
 * 为什么有这个文件（2026-09-20）
 * ══════════════════════════════════════════════════════════════
 *
 * 金恩来：「知识中心给了顾问上传文件时可以选择可见范围的能力，
 *   这个不合理！意思是员工可以上传文件不让老板看见，
 *   这个在成熟的咨询系统中有这个功能吗？」
 *
 * **没有。** 联网查了文档管理系统的通行做法，结论很一致：
 * 权限由管理员设定，不由上传者自由决定；而且
 * **公司账号所有者永远拥有完整可见性**（owner always has full visibility）。
 * 成熟系统里「机密文档」是有的，但它是由管理员按密级设定的，
 * 不是随便谁传个文件就能把老板挡在外面。
 *
 * 改之前，顾问上传时可以把「总经理」那个勾去掉 ——
 * 于是一份文件存进公司的知识库，而公司老板看不到。
 * 对一家 13 个人的咨询公司，这不是"隐私"，是责任链断了：
 * 老板要为交付质量负责，却看不到员工放进来的东西。
 *
 * ── 这里只定一条规矩 ──────────────────────────────────────────
 *
 * **上传的人可以往下收窄受众，但总经理和系统管理员始终看得到。**
 *
 * 而且这两个角色**不出现在选项里** —— 详见下面 ALWAYS_VISIBLE_ROLES
 * 那段：受众是业务概念，访问权是系统属性，两件事不该混在一排勾里。
 */

/**
 * 永远看得到的角色 —— **不出现在选项里**。
 *
 * 金恩来 2026-09-20 连着问了三个问题，三个判断都对：
 *   「把系统管理员的角色去掉，一般会设计这个范围吗？」
 *   「总经理若是默认都是可见的，还有保留的必要吗？」
 *   「还是说顾问不应该有选择可见范围的选项？」
 *
 * 第一版我把总经理做成一个**锁死的勾**，那是个半成品：
 * 一个点不动的选项框，只会让人以为界面坏了。
 *
 * 正确的形状是把两件事分开：
 *   · **受众**（谁需要看到这份文档来干活）—— 业务概念，可选
 *   · **访问权**（谁技术上看得到）—— 系统属性，不可选、不展示成选项
 *
 * 总经理是业务上必须看到的那个人（他为交付质量负责）；
 * 系统管理员是维护角色，本来就能碰到库里的东西 ——
 * 把他列成"受众"只会让「可见范围」这个词更含糊。
 * 两个都不该占选项位，用一句话说明就够了。
 */
export const ALWAYS_VISIBLE_ROLES = ['ADMIN', 'SYS_ADMIN'] as const;

/**
 * 可以由上传者选的受众 —— 四个业务角色。
 *
 * 为什么保留"顾问也能选"：13 个人的公司，财务资料不给顾问看这类
 * 需求是真实的。但语义要摆正 —— 是**「谁需要看」**，不是「谁不许看」，
 * 而且怎么选都绕不开上面那两个角色。
 */
export const SELECTABLE_AUDIENCE_ROLES = ['MANAGER', 'SALES', 'CONSULTANT', 'FINANCE'] as const;

/**
 * 把「永远可见」的角色强制并回去。
 *
 * 前端和服务端都要走这一份 —— 只在界面上锁是摆设，
 * 绕过界面直接调接口照样能把老板排除在外。
 */
export const enforceAlwaysVisible = (roles?: readonly string[] | null): string[] => {
  const picked = Array.isArray(roles) ? roles.filter(Boolean).map(String) : [];
  /*
    空数组在这个系统里的含义是「全员可见」（见 Knowledge.tsx 的 getAccessLabel），
    所以空的时候不要硬塞一个 ADMIN 进去 —— 那会把「全员可见」变成「只有总经理」，
    正好反了。
  */
  if (picked.length === 0) return [];
  const out = [...picked];
  for (const must of ALWAYS_VISIBLE_ROLES) {
    if (!out.includes(must)) out.push(must);
  }
  return out;
};

/** 这个角色的勾能不能取消（界面上用来置灰） */
export const isLockedRole = (roleId: string): boolean =>
  (ALWAYS_VISIBLE_ROLES as readonly string[]).includes(roleId);

/** 界面上那句说明。不写的话，人会以为"没勾老板就是老板看不到" */
export const LOCKED_ROLE_HINT = '总经理和系统管理员始终可见（公司知识库里的东西，负责人必须看得到）。下面选的是**还有谁需要看**。';

/**
 * 默认受众 = 四个业务角色全选，也就是全员可见。
 *
 * 金恩来：「默认要全员可见」。对的 —— 知识库的目的是让东西流通，
 * 收窄应该是**例外**，需要人主动做一次判断。
 * 默认收窄的系统最后都会变成「谁也不知道库里有什么」。
 */
export const DEFAULT_AUDIENCE = [...SELECTABLE_AUDIENCE_ROLES];
